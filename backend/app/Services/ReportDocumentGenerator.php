    public function buildCsv(string $filename, array $rows, array $report, array $metadata, array $branding): Response
    {
        $stream = fopen('php://memory', 'w+');
        fwrite($stream, "\xEF\xBB\xBF");

        foreach ($this->buildMetadataLines($report, $metadata, $branding) as $metaRow) {
            fputcsv($stream, $metaRow);
        }

        fputcsv($stream, []);
        fputcsv($stream, ['Executive Summary']);
        fputcsv($stream, ['Total Records', (string) ($metadata['record_count'] ?? count($rows))]);
        fputcsv($stream, ['Generated By', $metadata['generated_by_line'] ?? ($metadata['generated_by_name'] ?? 'System')]);
        fputcsv($stream, ['Generated By Role', $metadata['generated_by_role'] ?? 'N/A']);
        fputcsv($stream, ['Report Scope', $report['category'] ?? 'N/A']);
        fputcsv($stream, ['Reporting Period', $metadata['reporting_period'] ?? 'All Available Records']);
        fputcsv($stream, ['Status', 'Official']);
        fputcsv($stream, ['Printed On', $metadata['printed_on'] ?? $metadata['generated_at'] ?? 'N/A']);
        fputcsv($stream, ['Printed By', $metadata['printed_by_user'] ?? 'System']);
        fputcsv($stream, ['Timezone', $metadata['printed_timezone'] ?? 'East Africa Time (EAT) – Africa/Addis_Ababa (UTC+03:00)']);
        fputcsv($stream, []);

        if (! empty($rows)) {
            $headers = array_keys($rows[0]);
            fputcsv($stream, $headers);
            foreach ($rows as $row) {
                fputcsv($stream, array_map(fn ($value) => $this->normalizeValue($value), $row));
            }
        } else {
            fputcsv($stream, ['No data available']);
        }

        rewind($stream);
        $content = stream_get_contents($stream);
        fclose($stream);

        return response($content, 200, [
            'Content-Type' => 'text/csv; charset=utf-8',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
        ]);
    }

    public function buildXlsx(string $filename, array $rows, array $report, array $metadata, array $branding): Response
