    }

    public function buildDocx(string $filename, array $rows, array $report, array $metadata, array $branding): Response
    {
        $phpWord = new PhpWord();
        $section = $phpWord->addSection(['marginLeft' => 600, 'marginRight' => 600, 'marginTop' => 600, 'marginBottom' => 600]);

        $this->addDocxHeader($section, $report, $metadata, $branding);
        $section->addTextBreak(1);
        $this->addDocxExecutiveSummary($section, $report, $metadata, $rows);
        $section->addTextBreak(1);

        $table = $section->addTable(['borderSize' => 4, 'borderColor' => '1D4ED8', 'cellMargin' => 80, 'bgColor' => 'F8FAFC']);
        foreach ($this->buildMetadataLines($report, $metadata, $branding) as $line) {
            $table->addRow();
            $table->addCell(3200)->addText($line[0], ['bold' => true, 'color' => '0F172A']);
            $table->addCell(8600)->addText($line[1], ['color' => '334155']);
        }

        $section->addTextBreak(1);
        $detailsHeading = 'Export Details';

        $section->addText($detailsHeading, ['bold' => true, 'size' => 16, 'color' => '0F172A']);
        $section->addTextBreak(1);

        if (! empty($rows)) {
            if (count($rows) === 1 && in_array($report['category'] ?? '', ['delivery_document', 'delivery_form'], true)) {
                $row = $rows[0];
                $detailTable = $section->addTable(['borderSize' => 4, 'borderColor' => '94A3B8', 'cellMargin' => 80]);
                foreach ($row as $label => $value) {
                    $detailTable->addRow();
                    $detailTable->addCell(3200)->addText((string) $label, ['bold' => true, 'color' => '0F172A']);
                    $detailTable->addCell(8600)->addText($this->normalizeValue($value), ['color' => '334155']);
                }
            } else {
                $dataTable = $section->addTable(['borderSize' => 4, 'borderColor' => '94A3B8', 'cellMargin' => 80]);
                $dataTable->addRow();
                foreach (array_keys($rows[0]) as $header) {
                    $dataTable->addCell(2200)->addText((string) $header, ['bold' => true, 'color' => 'FFFFFF'], ['bgColor' => '1D4ED8']);
                }

                foreach ($rows as $row) {
                    $dataTable->addRow();
                    foreach (array_values($row) as $cell) {
                        $dataTable->addCell(2200)->addText($this->normalizeValue($cell), ['color' => '334155']);
                    }
                }
            }
        } else {
            $section->addText('No data available.', ['size' => 11, 'color' => '777777']);
        }

        $section->addTextBreak(1);
        $this->addDocxRevisionHistory($section, $metadata);
        $section->addTextBreak(1);
        $this->addDocxApprovalPanel($section, $metadata);
        $section->addTextBreak(1);
        $this->addDocxVerificationBlock($section, $metadata);

        $writer = new Word2007($phpWord);
        ob_start();
        $writer->save('php://output');
        $content = ob_get_clean();

        return response($content, 200, [
            'Content-Type' => 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
        ]);
    }

    public function buildPdf(string $filename, array $rows, array $report, array $metadata, array $branding, string $orientation = 'portrait', string $paperSize = 'A4'): Response
    {
        $qrPayload = $this->buildQrPayload($metadata);
        $qrDataUri = $this->buildQrCodeDataUri($qrPayload);
        $barcodeDataUri = $this->buildBarcodeDataUri($metadata['reference_number'] . '|' . ($metadata['verification_id'] ?? ''));

        $html = $this->buildPdfHtml($report, $rows, $metadata, $branding, $qrDataUri, $barcodeDataUri);

        $dompdf = new Dompdf();
        // Enable inline PHP for page numbering (dompdf page_text)
        $dompdf->getOptions()->set('isPhpEnabled', true);
        $dompdf->loadHtml($html);
        $dompdf->setPaper($paperSize, $orientation);
        $dompdf->render();

        return response($dompdf->output(), 200, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="' . $filename . '"',
        ]);
    }

