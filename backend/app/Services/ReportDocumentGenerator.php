            ->setDescription('System-generated report export with audit metadata and secure verification details.');

        $summarySheet = $spreadsheet->getActiveSheet();
        $summarySheet->setTitle('Report Summary');
        $summarySheet->mergeCells('A1:B1');
        $summarySheet->setCellValue('A1', strtoupper($report['title']));
        $summarySheet->getStyle('A1')->getFont()->setBold(true)->setSize(14)->getColor()->setRGB('0F172A');
        $summarySheet->getStyle('A1')->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('E0F2FE');

        $summarySheet->fromArray(['Field', 'Value'], null, 'A2');
        $summarySheet->fromArray($this->buildMetadataLines($report, $metadata, $branding), null, 'A3');
        $summarySheet->getStyle('A2:B2')->getFont()->setBold(true);
        $summarySheet->getStyle('A2:B2')->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('1D4ED8');
