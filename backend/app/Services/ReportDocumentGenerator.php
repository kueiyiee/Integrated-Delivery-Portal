            ['Company Registration Number', $branding['company_registration_number'] ?? 'N/A'],
            ['Company Address', $branding['company_address'] ?? 'N/A'],
            ['Company Website', $branding['company_website'] ?? 'N/A'],
            ['Support Email', $branding['support_email'] ?? 'N/A'],
            ['Generation Date', $metadata['generated_at'] ?? now()->setTimezone('Africa/Addis_Ababa')->format('l, d F Y • g:i:s A') . ' EAT (UTC+03:00)'],
            ['Environment', $metadata['environment'] ?? 'Production'],
            ['Confidentiality', $metadata['confidentiality'] ?? 'Confidential'],
