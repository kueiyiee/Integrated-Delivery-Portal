    private function buildApprovalBlockHtml(string $heading, array $fields): string
    {
        $html = '<div style="background:#ffffff;border:1px solid #cbd5e1;border-radius:12px;padding:14px;">';
        $html .= '<div style="font-weight:bold;color:#0f172a;margin-bottom:10px;">' . $heading . '</div>';
