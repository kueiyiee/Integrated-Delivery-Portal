            ['Generated By', $metadata['generated_by_line'] ?? ($metadata['generated_by_name'] ?? 'System')],
            ['Generated By Role', $metadata['generated_by_role'] ?? 'N/A'],
            ['Company Name', $metadata['company_name'] ?? ($branding['platform_name'] ?? 'Logistics Integration Portal')],
