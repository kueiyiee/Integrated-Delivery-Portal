        }

        $approvalSheet = $spreadsheet->createSheet();
        $approvalSheet->setTitle('Approval');
        $approvalSheet->setCellValue('A1', 'Authorized Export Approval');
        $approvalSheet->mergeCells('A1:D1');
        $approvalSheet->getStyle('A1')->getFont()->setBold(true)->setSize(14);
