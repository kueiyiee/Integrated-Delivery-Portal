    private function applyConditionalFormatting($sheet, array $rows): void
    {
        if (empty($rows)) {
            return;
        }

        $highestColumn = $sheet->getHighestColumn();
        $highestRow = $sheet->getHighestRow();
        $statusColumn = null;

        foreach (range('A', $highestColumn) as $column) {
            if (strtolower((string) $sheet->getCell($column . '1')->getValue()) === 'status') {
                $statusColumn = $column;
                break;
            }
        }

        if ($statusColumn !== null) {
            $sheet->getStyle("{$statusColumn}2:{$statusColumn}{$highestRow}")
                ->getFill()
                ->setFillType(Fill::FILL_SOLID)
                ->getStartColor()->setARGB('E0F2FE');
        }
    }

